export function getProduct(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProducts(slugs: string[]): Product[] {
  return slugs
    .map((s) => getProduct(s))
    .filter((p): p is Product => Boolean(p) && p!.inStock);
}

export const bestsellers = () => products.filter((p) => p.bestseller && p.inStock);
export const newProducts = () => products.filter((p) => p.isNew && p.inStock);
export const premiumProducts = () => products.filter((p) => p.premium && p.inStock);
